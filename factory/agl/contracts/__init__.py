"""Frozen R01 contracts; adapters implement these Protocols on their own branch."""
from typing import Protocol
from ..schemas import (Ack, AgentRegistration, ArtifactEvidence, ClaimProposal, Event,
                       Handoff, LeaseGrant, MemoryNote, ProviderSession, StateTransition,
                       TaskSpec, TaskTransition, UEM)


class Authenticator(Protocol):
    def __call__(self, credential: str) -> ProviderSession: ...


class EvidenceVerifier(Protocol):
    def __call__(self, evidence: ArtifactEvidence) -> bool:
        """Read actual immutable logs and verify hashes, command, SHA and exit status."""
        ...


class ProviderAdapter(Protocol):
    def probe(self, principal: str, scope: dict) -> dict: ...
    def read(self, work_ref: dict, cursor: str | None) -> dict: ...
    def publish(self, immutable_event: Event, idempotency_key: str) -> dict: ...
    def reread(self, receipt: dict) -> dict: ...
    def observe_schedule(self, agent_id: str) -> dict: ...
    def health(self, agent_id: str) -> dict: ...


class GitRepository(Protocol):
    def read_ref(self, repo: str, ref: str) -> dict: ...
    def read_file(self, repo: str, ref: str, path: str) -> dict: ...
    def write_immutable(self, path: str, content: bytes, idempotency_key: str) -> dict: ...
    def readback(self, receipt: dict) -> dict: ...
    def cas_publish_projection(self, expected_commit_sha: str, content: bytes) -> dict: ...
